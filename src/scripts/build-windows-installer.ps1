# Configure and compile Wireshark on Windows 11, then build the NSIS installer.
# Versions come from versions/WINDOWS11.env.
#
#   powershell -File src\scripts\build-windows-installer.ps1 -Check
#   powershell -File src\scripts\build-windows-installer.ps1 -Build
#   powershell -File src\scripts\build-windows-installer.ps1 -Installer
#
# With no switches, the script builds and runs tshark -v.
# -Installer includes the build, then the NSIS executable.

[CmdletBinding()]
param(
    [switch]$Check,
    [switch]$Build,
    [switch]$Test,
    [switch]$Installer,
    [switch]$Clean
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$script:Marker = 'Generated by compile-wireshark.sh for Packet Penguin plugins.'

function Import-VersionFile([string]$Path) {
    if (-not (Test-Path $Path)) {
        throw "version configuration not found: $Path"
    }
    Get-Content -Path $Path | ForEach-Object {
        $line = $_.Trim()
        if ($line -eq '' -or $line.StartsWith('#')) {
            return
        }
        if ($line -match '^([A-Za-z_][A-Za-z0-9_]*)=(.*)$') {
            Set-Item -Path "Env:$($Matches[1])" -Value $Matches[2]
        }
    }
}

function Find-VersionFile {
    $dir = $PSScriptRoot
    while ($dir -and $dir -ne [IO.Path]::GetPathRoot($dir)) {
        $candidate = Join-Path $dir 'versions\WINDOWS11.env'
        if (Test-Path $candidate) {
            return $candidate
        }
        $dir = Split-Path $dir -Parent
    }
    foreach ($root in @('C:\workspace', 'C:\opt\wireshark-build')) {
        $candidate = Join-Path $root 'versions\WINDOWS11.env'
        if (Test-Path $candidate) {
            return $candidate
        }
    }
    throw 'version configuration not found: versions/WINDOWS11.env'
}

function Test-InTreePlugin([string]$CmakeFile) {
    $text = Get-Content -Raw -Path $CmakeFile
    if ($text -notmatch 'include\s*\(\s*WiresharkPlugin\s*\)') {
        return $false
    }
    if ($text -match 'find_package\s*\(\s*Wireshark') {
        return $false
    }
    return $true
}

function Prepare-InTreePlugins([string]$SourceDir, [string]$PluginRoot) {
    $linkRoot = Join-Path $SourceDir 'packet-penguin-plugins'
    $custom = Join-Path $SourceDir 'CMakeListsCustom.txt'
    $stamp = Join-Path $linkRoot '.generated-by-compile-wireshark'
    $found = @()
    if (Test-Path $PluginRoot) {
        Get-ChildItem -Path $PluginRoot -Recurse -Filter 'CMakeLists.txt' -Depth 2 | ForEach-Object {
            if (Test-InTreePlugin $_.FullName) {
                $found += $_.Directory.FullName
            }
        }
    }
    if ($found.Count -eq 0) {
        if ((Test-Path $custom) -and (Select-String -Path $custom -SimpleMatch $script:Marker -Quiet)) {
            Remove-Item -Force $custom
        }
        if (Test-Path $stamp) {
            Remove-Item -Recurse -Force $linkRoot
        }
        Write-Output 'Dissector plugins: none'
        return
    }
    if ((Test-Path $custom) -and -not (Select-String -Path $custom -SimpleMatch $script:Marker -Quiet)) {
        throw "$custom already exists. Remove it so the Windows build can write the Packet Penguin plugin list."
    }
    if ((Test-Path $linkRoot) -and -not (Test-Path $stamp)) {
        throw "$linkRoot already exists. Remove it so the Windows build can link Packet Penguin plugins there."
    }
    if (Test-Path $linkRoot) {
        Remove-Item -Recurse -Force $linkRoot
    }
    New-Item -ItemType Directory -Force -Path $linkRoot | Out-Null
    Set-Content -Path $stamp -Value $script:Marker -Encoding ascii
    $lines = @("# $script:Marker", 'set(CUSTOM_PLUGIN_SRC_DIR')
    foreach ($plugin in $found) {
        $rel = $plugin.Substring($PluginRoot.TrimEnd('\').Length).TrimStart('\')
        $safe = ($rel -replace '[\\ ]', '__')
        $link = Join-Path $linkRoot $safe
        New-Item -ItemType Junction -Path $link -Target $plugin | Out-Null
        $lines += "  `"packet-penguin-plugins/$($safe -replace '\\','/')`""
    }
    $lines += ')'
    Set-Content -Path $custom -Value $lines -Encoding ascii
    Write-Output "In-tree plugins: $($found.Count)"
    Write-Output "Wireshark will compile them from $linkRoot"
}

function Import-VcVars {
    $vcvars = 'C:\BuildTools\VC\Auxiliary\Build\vcvars64.bat'
    if (-not (Test-Path $vcvars)) {
        $found = Get-ChildItem -Path 'C:\BuildTools','C:\Program Files\Microsoft Visual Studio\2022' -Filter 'vcvars64.bat' -Recurse -ErrorAction SilentlyContinue |
            Select-Object -First 1
        if (-not $found) {
            throw 'vcvars64.bat was not found. Build the Windows 11 compile image before this script.'
        }
        $vcvars = $found.FullName
    }
    $machine = [Environment]::GetEnvironmentVariable('Path', 'Machine')
    $user = [Environment]::GetEnvironmentVariable('Path', 'User')
    $env:Path = "$machine;$user"
    cmd /c "`"$vcvars`" >nul && set" | ForEach-Object {
        if ($_ -match '^(.*?)=(.*)$') {
            Set-Item -Path "Env:$($Matches[1])" -Value $Matches[2]
        }
    }
    if (-not (Get-Command msbuild -ErrorAction SilentlyContinue)) {
        throw 'msbuild was not placed on PATH by vcvars64.bat'
    }
}

$versionFile = Find-VersionFile
Import-VersionFile $versionFile
foreach ($name in @('WIRESHARK_VERSION','PACKET_PENGUIN_VERSION','WINDOWS_VERSION','INSTALLER_RELEASE','QT_VERSION')) {
    $value = [Environment]::GetEnvironmentVariable($name)
    if ([string]::IsNullOrWhiteSpace($value)) {
        throw "$name is unset in $versionFile"
    }
}
if ($env:WINDOWS_VERSION -ne '11') {
    throw "WINDOWS_VERSION in $versionFile is $($env:WINDOWS_VERSION), expected 11"
}
if ($env:SUPPORTED -ne '1') {
    throw "Windows $($env:WINDOWS_VERSION) is not supported by this repository ($versionFile)"
}

$srcRoot = Split-Path $PSScriptRoot -Parent
$sourceDir = Join-Path $srcRoot "wireshark-$($env:WIRESHARK_VERSION)"
$pluginDir = Join-Path $srcRoot 'plugins'
$buildRoot = Join-Path $srcRoot 'build\windows11'
$buildDir = Join-Path $buildRoot 'wireshark'
$logDir = Join-Path $buildRoot 'logs'
$artifactDir = Join-Path $srcRoot 'artifacts\installers\windows11'
$installerName = "wireshark-$($env:WIRESHARK_VERSION)-$($env:INSTALLER_RELEASE).ppv$($env:PACKET_PENGUIN_VERSION).win11.x64.exe"

Write-Output "Wireshark version: $($env:WIRESHARK_VERSION)"
Write-Output "Packet Penguin version: $($env:PACKET_PENGUIN_VERSION)"
Write-Output "Windows version: $($env:WINDOWS_VERSION)"
Write-Output "Installer release: $($env:INSTALLER_RELEASE)"
Write-Output "Qt version: $($env:QT_VERSION)"
Write-Output "Version file: $versionFile"
Write-Output "Wireshark sources: $sourceDir"
Write-Output "Build directory: $buildDir"
Write-Output "Installer: $(Join-Path $artifactDir $installerName)"

if ($Check) {
    if (-not (Test-Path (Join-Path $sourceDir 'CMakeLists.txt'))) {
        throw "Wireshark source directory not found for version $($env:WIRESHARK_VERSION)"
    }
    exit 0
}

if ($env:OS -ne 'Windows_NT') {
    throw 'The Windows 11 build runs on Windows. This host is not Windows.'
}

if (-not $Build -and -not $Test -and -not $Installer -and -not $Clean) {
    $Build = $true
    $Test = $true
}
if ($Installer) {
    $Build = $true
}

if ($Clean) {
    if (Test-Path $buildDir) {
        Remove-Item -Recurse -Force $buildDir
    }
}

if ($Build) {
    if (-not (Test-Path (Join-Path $sourceDir 'CMakeLists.txt'))) {
        throw "Wireshark source directory not found for version $($env:WIRESHARK_VERSION)"
    }
    Import-VcVars
    if (-not $env:WIRESHARK_QT6_PREFIX_PATH) {
        $env:WIRESHARK_QT6_PREFIX_PATH = Join-Path 'C:\Qt' (Join-Path $env:QT_VERSION 'msvc2022_64')
    }
    if (-not $env:WIRESHARK_BASE_DIR) {
        $env:WIRESHARK_BASE_DIR = 'C:\wireshark-libs'
    }
    New-Item -ItemType Directory -Force -Path $env:WIRESHARK_BASE_DIR,$buildDir,$logDir | Out-Null
    $env:WIRESHARK_VERSION_EXTRA = "-ppv$($env:PACKET_PENGUIN_VERSION)"
    Prepare-InTreePlugins $sourceDir $pluginDir
    Write-Output "CMake generator: Visual Studio 17 2022"
    & cmake -S $sourceDir -B $buildDir -G 'Visual Studio 17 2022' -A x64
    if ($LASTEXITCODE -ne 0) {
        throw "cmake failed with exit $LASTEXITCODE"
    }
    & cmake --build $buildDir --config RelWithDebInfo --parallel
    if ($LASTEXITCODE -ne 0) {
        throw "cmake --build failed with exit $LASTEXITCODE"
    }
}

if ($Installer) {
    Import-VcVars
    if (-not (Test-Path (Join-Path $buildDir 'CMakeCache.txt'))) {
        throw "Windows build directory is missing. Run -Build before -Installer: $buildDir"
    }
    & cmake --build $buildDir --config RelWithDebInfo --target wireshark_nsis_prep
    if ($LASTEXITCODE -ne 0) {
        throw "wireshark_nsis_prep failed with exit $LASTEXITCODE"
    }
    & cmake --build $buildDir --config RelWithDebInfo --target wireshark_nsis
    if ($LASTEXITCODE -ne 0) {
        throw "wireshark_nsis failed with exit $LASTEXITCODE"
    }
    $produced = @(Get-ChildItem -Path $buildDir -Recurse -Filter 'wireshark-*.exe' |
        Where-Object { $_.Name -notlike 'uninstall-*' -and $_.FullName -match 'packaging\\nsis' })
    if ($produced.Count -ne 1) {
        throw "expected one NSIS installer under $buildDir\packaging\nsis, found $($produced.Count)"
    }
    New-Item -ItemType Directory -Force -Path $artifactDir | Out-Null
    $dest = Join-Path $artifactDir $installerName
    Copy-Item -Force $produced[0].FullName $dest
    Write-Output "Installer: $dest"
}

if ($Test) {
    $tshark = Join-Path $buildDir 'run\RelWithDebInfo\tshark.exe'
    if (-not (Test-Path $tshark)) {
        throw "tshark was not built at $tshark"
    }
    Write-Output "tshark: $tshark"
    & $tshark -v
    if ($LASTEXITCODE -ne 0) {
        throw "tshark -v failed with exit $LASTEXITCODE"
    }
}
